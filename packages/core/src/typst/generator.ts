import type { ResolvedConfig } from "../config/config.js";
import type { Block, TableMerge } from "../model/block.js";
import type { Provision } from "../model/provision.js";
import type { Document } from "../model/document.js";
import type { Figure } from "../model/figure.js";
import type { ChangeSummary } from "../git/change-summary.js";
import { InlineConverter } from "./inline-converter.js";
import { DEFAULT_HEADING_FORMAT } from "../config/config.js";
import { escapeLead, escapeTypst, typstString } from "./text.js";

export interface TypstOptions {
  /** Import path for the letterhead template as Typst should see it, e.g. "/dist/_template/letterhead.typ". */
  templateImport: string;
  /**
   * Maps a path to the form Typst should use. `figure` paths are repo-relative (already resolved
   * against the document); `logo` paths are relative to the config directory. Default: identity.
   */
  resolveAsset?: (path: string, kind: "logo" | "figure") => string;
  /** When set (and not empty), a "Summary of changes" page is appended. */
  changeSummary?: ChangeSummary;
}

/** Renders a document to some output format. */
export interface DocumentGenerator {
  generate(doc: Document): string;
}

export class TypstGenerator implements DocumentGenerator {
  private readonly resolve: (path: string, kind: "logo" | "figure") => string;

  constructor(
    private readonly config: ResolvedConfig,
    private readonly options: TypstOptions,
  ) {
    this.resolve = options.resolveAsset ?? ((p) => p);
  }

  generate(doc: Document): string {
    return new DocumentRenderer(doc, this.config, this.options.templateImport, this.resolve, this.options.changeSummary).render();
  }
}

/** Renders one document. Stateless apart from the document it was built for. */
class DocumentRenderer {
  private readonly inline: InlineConverter;

  constructor(
    private readonly doc: Document,
    private readonly config: ResolvedConfig,
    private readonly templateImport: string,
    private readonly resolve: (path: string, kind: "logo" | "figure") => string,
    private readonly summary?: ChangeSummary,
  ) {
    this.inline = new InlineConverter(doc);
  }

  render(): string {
    const out = [...this.header()];
    for (const provision of this.doc.provisions) {
      if (provision.id.isBlank) continue;
      out.push(...this.provision(provision), "");
    }
    if (this.summary && !this.summary.isEmpty) out.push(...this.summaryPage(this.summary), "");
    return out.join("\n");
  }

  private summaryPage(s: ChangeSummary): string[] {
    return [
      "#pagebreak()",
      `#text(size: 14pt, weight: "bold")[Summary of changes]`,
      "#v(0.6em)",
      ...(s.fromVersion ? [`Changes since version ${escapeTypst(s.fromVersion)}.`, "#v(0.4em)"] : []),
      `#list(${s.items.map((i) => `[${escapeTypst(i)}]`).join(", ")})`,
    ];
  }

  /** Cover page on? The frontmatter `cover:` key wins over the config default. */
  private get hasCover(): boolean {
    return this.doc.coverFlag ?? this.config.cover.enabled;
  }

  /** Table of contents on? Default: only with a cover; `toc:` in the frontmatter wins. */
  private get hasToc(): boolean {
    return this.doc.tocFlag ?? this.hasCover;
  }

  private coverTemplateImport(): string {
    return this.templateImport.replace(/[^/]*$/, "cover.typ");
  }

  private header(): string[] {
    const { doc, config } = this;
    const b = config.branding;
    const lines = [
      "// Generated by docengine. Do not edit; edit the Markdown source instead.",
      `#import ${typstString(this.templateImport)}: letterhead, provision`,
      ...(this.hasCover ? [`#import ${typstString(this.coverTemplateImport())}: cover`] : []),
      `#set figure(supplement: [${escapeTypst(config.images.label)}])`,
      "#show: letterhead.with(",
      `  fir-name: ${typstString(b.firName)},`,
    ];
    if (b.logo) lines.push(`  logo: image(${typstString(this.resolve(b.logo, "logo"))}, height: 1.3cm),`);
    lines.push(
      `  primary: rgb(${typstString(b.colors.primary)}),`,
      `  accent: rgb(${typstString(b.colors.accent)}),`,
      `  font: ${typstString(b.font)},`,
      `  footer-text: ${typstString(b.footer)},`,
      `  title: ${typstString(doc.title)},`,
      `  short: ${typstString(doc.short)},`,
      `  group: ${typstString(doc.group)},`,
      `  version: ${typstString(doc.version)},`,
      `  effective-date: ${typstString(doc.effectiveDate)},`,
    );
    if (doc.expiryDate) lines.push(`  expiry-date: ${typstString(doc.expiryDate)},`);
    if (doc.effectiveTime) lines.push(`  effective-time: ${typstString(doc.effectiveTime)},`);
    if (b.colors.highlight) lines.push(`  highlight-color: rgb(${typstString(b.colors.highlight)}),`);
    if (this.hasToc) lines.push(`  toc-depth: ${Math.max(1, config.toc.depth - this.levelOffset)},`, `  toc-title: ${typstString(config.toc.title)},`);
    if (this.hasCover) lines.push(...this.coverArgument());
    lines.push(`  draft: ${doc.isDraft ? "true" : "false"},`, ")", "");
    return lines;
  }

  /** The `cover:` argument: a call into the (overridable) cover template. */
  private coverArgument(): string[] {
    const { doc, config } = this;
    const b = config.branding;
    const c = config.cover;
    const logo = c.logo ?? b.logo;
    const notice = doc.notice ?? c.notice;
    return [
      "  cover: cover(",
      `    fir-name: ${typstString(c.firName ?? b.firName)},`,
      ...(logo ? [`    logo: image(${typstString(this.resolve(logo, "logo"))}, height: 4.5cm),`] : []),
      `    primary: rgb(${typstString(c.colors.primary ?? b.colors.primary)}),`,
      `    accent: rgb(${typstString(c.colors.accent ?? b.colors.accent)}),`,
      `    font: ${typstString(b.font)},`,
      `    title: ${typstString(doc.title)},`,
      ...(doc.subtitle ? [`    subtitle: ${typstString(doc.subtitle)},`] : []),
      `    version: ${typstString(doc.version)},`,
      `    effective-date: ${typstString(doc.effectiveDate)},`,
      ...(doc.effectiveTime ? [`    effective-time: ${typstString(doc.effectiveTime)},`] : []),
      ...(notice ? [`    notice: ${typstString(notice)},`] : []),
      `    draft: ${doc.isDraft ? "true" : "false"},`,
      "  ),",
    ];
  }

  private provision(c: Provision): string[] {
    const args = [typstString(c.id.text), String(c.depth), `level-label: ${typstString(c.level.label)}`];
    if (c.level.isParenthesised) args.push(`label: ${typstString(c.id.label)}`);
    else if (!this.isHeading(c)) {
      const parentText = c.id.parent?.text ?? "";
      const margin = parentText && c.id.text.startsWith(parentText) ? c.id.text.slice(parentText.length) : c.id.text;
      args.push(`label: ${typstString(margin)}`);
    }
    // The template treats depth <= 3 as a heading, which is the cars scheme. Other schemes say so explicitly.
    if (this.doc.scheme.topLevels !== 3) args.push(`structural-heading: ${c.depth <= this.doc.scheme.topLevels}`);
    if (c.level.italicLabel) args.push("italic-label: true");
    if (!c.level.showLabel) args.push("show-label: false");
    if (!this.isHeading(c) && c.level.indent > 0) args.push(`indent: ${c.level.indent}`);
    if (c.repealed) args.push("repealed: true");
    if (c.title) args.push(`title: [${this.inline.convert(c.title)}]`);
    args.push(...this.headingArguments(c));
    if (this.levelOffset > 0 && this.isHeading(c)) args.push(`level-offset: ${this.levelOffset}`);
    if (this.hasFootnote(c)) args.push("whole: true");

    const keepNext = this.config.keepWithNext && c.keep !== "break";
    const body = c.blocks.map((b, i) => {
      const text = this.block(b);
      // A paragraph that introduces a figure stays on the page where the figure starts.
      return keepNext && b.type === "paragraph" && c.blocks[i + 1]?.type === "figure" ? `#block(sticky: true)[${text}]` : text;
    });
    if (c.repealed && c.repealNote) body.push(this.inline.convert(c.repealNote));
    const indented = body.join("\n\n").split("\n").map((l) => (l ? "  " + l : l)).join("\n");
    return [`#provision(${args.join(", ")})[`, indented, `] <${c.id.typstLabel}>`];
  }

  /**
   * Does the provision text cite a footnote? Such a margin-ID provision is laid out as one unbreakable block: Typst
   * cannot move a footnote reference out of a page-spanning grid row, so the note would land on the wrong page.
   */
  private hasFootnote(c: Provision): boolean {
    if (this.isHeading(c)) return false;
    return this.doc.footnoteReferences.some((r) => r.provisionId?.text === c.id.text && !r.insideFootnote);
  }

  /** Should the provision start a new page? `null` when the template default (no break) applies. */
  private startsPage(c: Provision): boolean | null {
    if (c.page === "page") return true;
    if (c.page === "nopage") return false;
    const automatic = this.automaticPageBreak(c);
    const choice = c.level.pageBreak;
    if (choice === true) return this.isHeading(c) ? true : null;
    if (choice === false) return automatic ? false : null;
    return automatic ? true : null;
  }

  /** Depth rule: with a table of contents, headings down to `pageBreakBefore` start a new page. */
  private automaticPageBreak(c: Provision): boolean {
    const depth = this.config.headings.pageBreakBefore;
    return depth !== false && this.hasToc && this.isHeading(c) && c.depth <= depth;
  }

  /** Levels above the shallowest heading that the document never declares (so the outline starts at level 1). */
  private get levelOffset(): number {
    let min = this.doc.scheme.topLevels;
    for (const p of this.doc.provisions) if (p.id.isWellFormed && this.isHeading(p) && p.depth < min) min = p.depth;
    return min - 1;
  }

  /** Is this provision rendered as a heading (rather than a margin-ID paragraph)? */
  private isHeading(c: Provision): boolean {
    return c.depth <= this.doc.scheme.topLevels || (!!c.title && c.depth <= this.config.headings.maxDepth);
  }

  /** Arguments that only appear when they differ from the template defaults, so default output is stable. */
  private headingArguments(c: Provision): string[] {
    const out: string[] = [];
    if (c.keep === "keep") out.push("keep: true");
    else if (c.keep === "break" || (!this.config.keepWithNext && this.isHeading(c))) out.push("keep: false");
    const pageBreak = this.startsPage(c);
    if (pageBreak !== null) out.push(`page-break: ${pageBreak}`);
    if (c.title || c.depth <= this.doc.scheme.topLevels) {
      const { format, maxDepth } = this.config.headings;
      if (format !== DEFAULT_HEADING_FORMAT) out.push(`heading-format: ${typstString(format)}`);
      if (maxDepth !== 3) out.push(`heading-depth: ${maxDepth}`);
    }
    return out;
  }

  private block(b: Block): string {
    switch (b.type) {
      case "paragraph":
        return escapeLead(this.inline.convert(b.text));
      case "list": {
        const fn = b.ordered ? "#enum" : "#list";
        return `${fn}(${b.items.map((i) => `[${this.inline.convert(i)}]`).join(", ")})`;
      }
      case "table": {
        const cols = b.header.length;
        const grid = this.tableGrid(b, cols);
        const header = grid.slice(0, 1)[0]!;
        const rows = grid.slice(1).map((r) => r.join(", "));
        return [
          `#table(columns: ${cols}, align: (${b.align.join(", ")}${cols === 1 ? "," : ""}),`,
          `  table.header(${header.join(", ")}),`,
          ...rows.map((r) => `  ${r},`),
          ")",
        ].join("\n");
      }
      case "code":
        return `#raw(block: true, ${typstString(b.text)})`;
      case "figure":
        return this.figure(b.figure);
    }
  }

  /**
   * Typst cells for the header (first) and body rows. Cells merged into a neighbour (`||` to the
   * left, `^` above) are dropped and the cell they merged into gets a colspan / rowspan.
   */
  private tableGrid(b: Extract<Block, { type: "table" }>, cols: number): string[][] {
    interface Cell { text: string; colspan: number; rowspan: number }
    const texts = [b.header, ...b.rows];
    const merges: TableMerge[][] = [b.merge?.header ?? [], ...(b.merge?.rows ?? [])];
    const grid: (Cell | null)[][] = [];
    for (let r = 0; r < texts.length; r++) {
      const row: (Cell | null)[] = [];
      for (let c = 0; c < cols; c++) {
        const merge = merges[r]?.[c] ?? "none";
        const text = texts[r]?.[c] ?? "";
        let target: Cell | undefined;
        if (merge === "left" && c > 0) {
          let k = c - 1;
          while (k > 0 && row[k] === null && merges[r]?.[k] === "left") k--;
          target = row[k] ?? undefined;
          if (target) target.colspan++;
        } else if (merge === "up" && r > 1) {
          let k = r - 1;
          while (k > 1 && grid[k]![c] === null && merges[k]?.[c] === "up") k--;
          target = grid[k]![c] ?? undefined;
          if (target && target.colspan === 1) target.rowspan++;
          else target = undefined;
        }
        row.push(target ? null : { text, colspan: 1, rowspan: 1 });
      }
      grid.push(row);
    }
    return grid.map((row) =>
      row.flatMap((cell) => {
        if (!cell) return [];
        const content = `[${this.inline.convert(cell.text)}]`;
        const spans = [...(cell.colspan > 1 ? [`colspan: ${cell.colspan}`] : []), ...(cell.rowspan > 1 ? [`rowspan: ${cell.rowspan}`] : [])];
        return [spans.length ? `table.cell(${spans.join(", ")})${content}` : content];
      }),
    );
  }

  private figure(f: Figure): string {
    const path = this.resolve(f.sourcePath(this.doc.file), "figure");
    const img = [typstString(path), `alt: ${typstString(f.caption)}`];
    if (f.width) img.push(`width: ${f.width}`);
    const args = [`image(${img.join(", ")})`, `caption: [${this.inline.convert(f.caption)}]`];
    if (f.placement === "float") args.push("placement: auto");
    let fig = `#figure(${args.join(", ")})`;
    if (f.typstLabel) fig += ` <${f.typstLabel}>`;
    return f.align ? `#align(${f.align})[${fig}]` : fig;
  }
}

/** Facade over `TypstGenerator`. */
export function generateTypst(doc: Document, config: ResolvedConfig, options: TypstOptions): string {
  return new TypstGenerator(config, options).generate(doc);
}
