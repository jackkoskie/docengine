// Bundles the extension into a single CommonJS file (dist/extension.cjs) with esbuild.
// `vscode` stays external; `@jackkoskie/docengine-core` (and its dependencies) are bundled from source,
// so the package does not need core to be built first.
import { build } from "esbuild";
import { copyFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, "..");
const watch = process.argv.includes("--watch");

const options = {
  entryPoints: [resolve(pkg, "src/extension.ts")],
  outfile: resolve(pkg, "dist/extension.cjs"),
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node20",
  external: ["vscode"],
  alias: { "@jackkoskie/docengine-core": resolve(pkg, "../core/src/index.ts") },
  sourcemap: true,
  minify: !watch,
  legalComments: "none",
  logLevel: "info",
};

// Bundle the frontmatter JSON Schema (generated by `docengine schema`) for the modeline command.
const schema = resolve(pkg, "../../schema/frontmatter.schema.json");
if (existsSync(schema)) {
  mkdirSync(resolve(pkg, "schema"), { recursive: true });
  copyFileSync(schema, resolve(pkg, "schema/frontmatter.schema.json"));
}
copyFileSync(resolve(pkg, "../../LICENSE"), resolve(pkg, "LICENSE"));
copyFileSync(resolve(pkg, "../../NOTICE"), resolve(pkg, "NOTICE"));

if (watch) {
  const { context } = await import("esbuild");
  const ctx = await context(options);
  await ctx.watch();
} else {
  await build(options);
}
